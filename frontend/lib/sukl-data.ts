export function getDrugPresetByCode(suklCode: string): DrugPreset | null {
  const clean = suklCode.trim();
  // Map alias codes for Ritalin
  if (["0015642", "0015643", "15642", "15643", "0268766", "268766"].includes(clean)) {
    return CLINICAL_DRUGS.ritalin;
  }
  // Map all registered packages of Livizux (70mg 30 cps, 70mg 100 cps, 50mg, 30mg)
  if (["0265886", "0265887", "0265888", "265886", "265887", "265888"].includes(clean)) {
    return CLINICAL_DRUGS.livizux;
  }
  for (const preset of Object.values(CLINICAL_DRUGS)) {
    if (preset.defaultSuklCode === clean) {
      return preset;
    }
  }
  return null;
}

export function getDrugPresetById(id: string): DrugPreset | null {
  const clean = id.toLowerCase().trim().replace(/^preset_/, "");
  return CLINICAL_DRUGS[clean] || null;
}

export function getSuklDetailByCode(suklCode: string): SuklPackageDetail | null {
  const clean = suklCode.trim();
  const aliasMap: Record<string, string> = {
    "0015642": "0268766",
    "0015643": "0268766",
    "15642": "0268766",
    "15643": "0268766",
  };
  const effective = aliasMap[clean] || clean;
  if (SUKL_DATABASE[effective]) {
    return SUKL_DATABASE[effective];
  }
  // Try 7-digit zero padding
  const padded = effective.padStart(7, "0");
  if (SUKL_DATABASE[padded]) {
    return SUKL_DATABASE[padded];
  }
  return null;
}

export function searchSuklCatalog(query: string): Array<{ kodSukl: string; nazev: string; doplnek: string; matchedId?: string }> {
  const q = query.trim().toLowerCase();
  if (!q) return [];

  const results: Array<{ kodSukl: string; nazev: string; doplnek: string; matchedId?: string }> = [];

  for (const [code, item] of Object.entries(SUKL_DATABASE)) {
    if (
      code.includes(q) ||
      item.nazev.toLowerCase().includes(q) ||
      item.doplnek.toLowerCase().includes(q) ||
      item.atcNazev.toLowerCase().includes(q)
    ) {
      results.push({
        kodSukl: item.kodSukl,
        nazev: item.nazev,
        doplnek: item.doplnek,
      });
    }
  }

  for (const preset of Object.values(CLINICAL_DRUGS)) {
    if (
      preset.name.toLowerCase().includes(q) ||
      preset.substance.toLowerCase().includes(q) ||
      preset.id.toLowerCase().includes(q)
    ) {
      if (!results.some((r) => r.kodSukl === preset.defaultSuklCode)) {
        results.push({
          kodSukl: preset.defaultSuklCode,
          nazev: preset.name,
          doplnek: preset.category,
          matchedId: preset.id,
        });
      }
    }
  }

  return results;
}
